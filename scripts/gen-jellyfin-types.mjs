#!/usr/bin/env node
/**
 * Generate `src/lib/jellyfinOpenApi.d.ts` — the Jellyfin server's OWN types for
 * the DTOs Cadence reads, straight from its OpenAPI spec. Cadence still hand-
 * models the small subset it consumes (src/lib/jellyfinTypes.ts, kept small on
 * purpose — no heavy SDK), but that subset is now CHECKED against these at
 * compile time, so a field Jellyfin renames, retypes or makes nullable is a type
 * error, not a production surprise.
 *
 *   node scripts/gen-jellyfin-types.mjs <openapi.json path or URL>
 *
 * The hermetic e2e server serves the spec of the exact version CI tests against:
 *   scripts/e2e-jellyfin.sh up && node scripts/gen-jellyfin-types.mjs http://localhost:8196/api-docs/openapi.json
 *
 * Emits the transitive closure of ROOTS only (not the whole 350-schema API).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const ROOTS = [
  'BaseItemDto',
  'BaseItemDtoQueryResult',
  'UserItemDataDto',
  'AuthenticationResult',
  'LyricDto',
  'PublicSystemInfo',
];
const OUT = new URL('../src/lib/jellyfinOpenApi.d.ts', import.meta.url);

const source = process.argv[2];
if (!source) {
  console.error('usage: gen-jellyfin-types.mjs <openapi.json path or URL>');
  process.exit(1);
}
const spec = source.startsWith('http')
  ? await (await fetch(source)).json()
  : JSON.parse(readFileSync(source, 'utf8'));
const schemas = spec.components.schemas;

const refName = (ref) => ref.split('/').pop();
const deps = (schema, acc = new Set()) => {
  if (!schema || typeof schema !== 'object') return acc;
  if (schema.$ref) acc.add(refName(schema.$ref));
  for (const v of Object.values(schema)) {
    if (Array.isArray(v)) v.forEach((x) => deps(x, acc));
    else if (typeof v === 'object') deps(v, acc);
  }
  return acc;
};

const closure = new Set();
const queue = [...ROOTS];
while (queue.length) {
  const name = queue.shift();
  if (closure.has(name)) continue;
  if (!schemas[name]) throw new Error(`schema ${name} not in spec`);
  closure.add(name);
  for (const d of deps(schemas[name])) if (!closure.has(d)) queue.push(d);
}

function tsType(s) {
  if (!s) return 'unknown';
  const nullable = s.nullable ? ' | null' : '';
  if (s.$ref) return refName(s.$ref) + nullable;
  if (s.allOf) return s.allOf.map(tsType).join(' & ') + nullable;
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(tsType).join(' | ') + nullable;
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ') + nullable;
  switch (s.type) {
    case 'string':
      return 'string' + nullable;
    case 'integer':
    case 'number':
      return 'number' + nullable;
    case 'boolean':
      return 'boolean' + nullable;
    case 'array':
      return `Array<${tsType(s.items)}>` + nullable;
    case 'object':
      if (s.properties) return `{ ${props(s)} }` + nullable;
      return (
        `Record<string, ${s.additionalProperties ? tsType(s.additionalProperties) : 'unknown'}>` +
        nullable
      );
    default:
      return 'unknown' + nullable;
  }
}

function props(s) {
  const required = new Set(s.required ?? []);
  return Object.entries(s.properties ?? {})
    .map(([k, v]) => `${JSON.stringify(k)}${required.has(k) ? '' : '?'}: ${tsType(v)};`)
    .join(' ');
}

const lines = [
  `// GENERATED by scripts/gen-jellyfin-types.mjs from Jellyfin ${spec.info?.version ?? '?'}'s`,
  '// OpenAPI spec. Do not edit by hand — regenerate.',
  '',
];
for (const name of [...closure].sort()) {
  const s = schemas[name];
  const doc = s.description
    ? `/** ${s.description.replace(/\*\//g, '*\\/').replace(/\s+/g, ' ')} */\n`
    : '';
  if (s.type === 'object' || s.properties) {
    lines.push(`${doc}export interface ${name} {`);
    const required = new Set(s.required ?? []);
    for (const [k, v] of Object.entries(s.properties ?? {})) {
      lines.push(`  ${JSON.stringify(k)}${required.has(k) ? '' : '?'}: ${tsType(v)};`);
    }
    lines.push('}', '');
  } else {
    lines.push(`${doc}export type ${name} = ${tsType(s)};`, '');
  }
}
writeFileSync(OUT, lines.join('\n'));
console.log(`gen-jellyfin-types: ${closure.size} schemas → ${OUT.pathname}`);
